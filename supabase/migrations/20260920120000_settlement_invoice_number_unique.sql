-- Взаиморасчёты: номер счёта уникален по договору внутри компании.
--
-- До этого уникальность проверял только веб — отдельным запросом перед записью.
-- При одновременном сохранении двух одинаковых номеров проверка у обоих
-- проходила, и в базе оказывался дубль. Теперь дубль не даст создать индекс.
--
-- Индекс частичный: пустой номер дублем не считается — правило совпадает
-- с приложением, которое требует заполнить номер, но не ломает старые записи.
-- Веб пишет номер уже обрезанным от пробелов, поэтому btrim в условии нужен
-- только как страховка от внешних писателей.

BEGIN;

CREATE UNIQUE INDEX IF NOT EXISTS settlement_operations_invoice_number_unique
    ON public.settlement_operations (company_id, contract_id, invoice_number)
    WHERE btrim(invoice_number) <> '';

COMMENT ON INDEX public.settlement_operations_invoice_number_unique IS
    'Номер счёта уникален в пределах договора компании (непустые номера).';

COMMIT;
