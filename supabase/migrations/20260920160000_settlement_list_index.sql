-- Взаиморасчёты: индекс под порядок реестра.
--
-- Реестр всегда фильтрует счета по компании и сортирует по дате счёта, а вторым
-- ключом идёт идентификатор — он делает порядок строгим, чтобы строки не
-- повторялись и не пропадали между страницами. Подходящего индекса не было:
-- база читала счета компании и сортировала их при каждом запросе.
--
-- Колонки и направления совпадают с ORDER BY по умолчанию, поэтому сортировка
-- не нужна. Для других колонок (контрагент, объект, суммы) база сортирует
-- результат как и раньше — там порядок зависит от связанных таблиц.

BEGIN;

CREATE INDEX IF NOT EXISTS idx_settlement_operations_company_date
    ON public.settlement_operations (company_id, invoice_date DESC, id ASC);

COMMENT ON INDEX public.idx_settlement_operations_company_date IS
    'Порядок реестра взаиморасчётов: компания, дата счёта (по убыванию), идентификатор.';

COMMIT;
